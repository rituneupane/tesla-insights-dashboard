"""Run data checks and build the static dashboard data file.

Run from the repo root:  python analysis/build.py
- prints and writes data/checks.csv
- writes docs/data.js (used by docs/index.html)
"""
import csv, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)


def num(v):
    return float(v) if v not in ("", None) else None


annual = [{k: (v if k == "notes" else num(v)) for k, v in r.items()} for r in csv.DictReader(open(P("data", "tesla_annual.csv")))]
quarterly = [{k: (v if k == "period" else num(v)) for k, v in r.items()} for r in csv.DictReader(open(P("data", "tesla_quarterly.csv")))]

checks = []
def check(name, left, right, tol):
    checks.append(dict(check=name, value=round(left, 2), should_equal=round(right, 2),
                       difference=round(left - right, 2), result="PASS" if abs(left - right) <= tol else "FAIL"))

for r in annual:
    y = int(r["year"])
    seg = r["automotive_revenue_b"] + r["energy_revenue_b"] + r["services_revenue_b"]
    check(f"{y} segments = total revenue ($B)", seg, r["total_revenue_b"], 0.02)
    if r["model_3y_deliveries"] is not None:
        check(f"{y} 3/Y + other = deliveries", r["model_3y_deliveries"] + r["other_deliveries"], r["deliveries"], 0)
for y in sorted({q["period"][:4] for q in quarterly}):
    qs = [q for q in quarterly if q["period"].startswith(y)]
    a = next(r for r in annual if int(r["year"]) == int(y))
    for col in ["total_deliveries", "model_3y_deliveries", "other_deliveries"]:
        acol = "deliveries" if col == "total_deliveries" else col
        check(f"{y} quarters = year ({col})", sum(q[col] for q in qs), a[acol], 0)
for q in quarterly:
    check(f"{q['period']} 3/Y + other = total", q["model_3y_deliveries"] + q["other_deliveries"], q["total_deliveries"], 0)

with open(P("data", "checks.csv"), "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(checks[0])); w.writeheader(); w.writerows(checks)
fails = [c for c in checks if c["result"] != "PASS"]
print(f"{len(checks)} checks, {len(fails)} failed")
for c in fails: print("FAIL", c)

with open(P("docs", "data.js"), "w") as f:
    f.write("// Generated by analysis/build.py from data/*.csv. Do not edit by hand.\n")
    f.write("const ANNUAL = " + json.dumps(annual) + ";\n")
    f.write("const QUARTERLY = " + json.dumps(quarterly) + ";\n")
    f.write("const CHECKS = " + json.dumps(checks) + ";\n")
